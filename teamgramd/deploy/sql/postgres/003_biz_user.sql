);
CREATE INDEX IF NOT EXISTS unregistered_contacts_phone_idx ON unregistered_contacts (phone, imported);

CREATE OR REPLACE FUNCTION biz_user_set_updated_at()
RETURNS TRIGGER LANGUAGE plpgsql AS $$
BEGIN
    NEW.updated_at = CURRENT_TIMESTAMP;
    RETURN NEW;
END;
$$;

DROP TRIGGER IF EXISTS users_set_updated_at ON users;
CREATE TRIGGER users_set_updated_at BEFORE UPDATE ON users FOR EACH ROW EXECUTE FUNCTION biz_user_set_updated_at();
DROP TRIGGER IF EXISTS username_set_updated_at ON username;
CREATE TRIGGER username_set_updated_at BEFORE UPDATE ON username FOR EACH ROW EXECUTE FUNCTION biz_user_set_updated_at();
DROP TRIGGER IF EXISTS user_contacts_set_updated_at ON user_contacts;
CREATE TRIGGER user_contacts_set_updated_at BEFORE UPDATE ON user_contacts FOR EACH ROW EXECUTE FUNCTION biz_user_set_updated_at();
