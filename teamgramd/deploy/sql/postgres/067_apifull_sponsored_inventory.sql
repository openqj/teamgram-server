-- PostgreSQL 18 deployment-owned sponsored-message inventory.
-- The inventory payload is a canonical Layer 229 constructor encoded as JSON.
-- No row means that this deployment has no inventory for the requested key;
-- callers must fail closed instead of manufacturing an empty result.
CREATE TABLE IF NOT EXISTS apifull_sponsored_inventory (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    inventory_type TEXT NOT NULL CHECK (inventory_type IN ('peers', 'messages')),
    query TEXT NOT NULL DEFAULT '',
    peer_key TEXT NOT NULL DEFAULT '',
    payload JSONB NOT NULL,
    active BOOLEAN NOT NULL DEFAULT TRUE,
    starts_at TIMESTAMPTZ NULL,
    ends_at TIMESTAMPTZ NULL,
    updated_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT apifull_sponsored_inventory_payload_object
        CHECK (jsonb_typeof(payload) = 'object'),
    CONSTRAINT apifull_sponsored_inventory_scope_key
        CHECK ((inventory_type = 'peers' AND peer_key = '') OR
               (inventory_type = 'messages' AND query = '')),
    CONSTRAINT apifull_sponsored_inventory_valid_window
        CHECK (ends_at IS NULL OR starts_at IS NULL OR ends_at > starts_at)
);

CREATE UNIQUE INDEX IF NOT EXISTS apifull_sponsored_inventory_peers_key
    ON apifull_sponsored_inventory (inventory_type, query)
    WHERE inventory_type = 'peers';

CREATE UNIQUE INDEX IF NOT EXISTS apifull_sponsored_inventory_messages_key
    ON apifull_sponsored_inventory (inventory_type, peer_key)
    WHERE inventory_type = 'messages';

CREATE INDEX IF NOT EXISTS idx_apifull_sponsored_inventory_active
    ON apifull_sponsored_inventory (inventory_type, active, starts_at, ends_at);
