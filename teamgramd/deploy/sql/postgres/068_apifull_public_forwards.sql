-- Public-forward analytics owned by APIFull.
--
-- A row is written by the authoritative message/forward consumer (or by an
-- import that has verified the source and destination message).  Statistics
-- reads never infer a forward from counters or fabricate an empty provider
-- response; an absent row is the durable "no public forward" result.
CREATE TABLE IF NOT EXISTS apifull_public_forward_message (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    source_channel_id BIGINT NOT NULL,
    source_message_id INTEGER NOT NULL,
    destination_peer_type SMALLINT NOT NULL,
    destination_peer_id BIGINT NOT NULL,
    destination_message_id INTEGER NOT NULL,
    message_date BIGINT NOT NULL,
    message_json JSONB NOT NULL,
    created_at BIGINT NOT NULL,
    UNIQUE (source_channel_id, source_message_id, destination_peer_type,
            destination_peer_id, destination_message_id)
);

CREATE INDEX IF NOT EXISTS apifull_public_forward_message_lookup
    ON apifull_public_forward_message (source_channel_id, source_message_id, id);

CREATE TABLE IF NOT EXISTS apifull_public_forward_story (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    source_user_id BIGINT NOT NULL,
    source_story_id INTEGER NOT NULL,
    destination_peer_type SMALLINT NOT NULL,
    destination_peer_id BIGINT NOT NULL,
    destination_story_id INTEGER NOT NULL,
    story_json JSONB NOT NULL,
    peer_json JSONB NOT NULL,
    created_at BIGINT NOT NULL,
    UNIQUE (source_user_id, source_story_id, destination_peer_type,
            destination_peer_id, destination_story_id)
);

CREATE INDEX IF NOT EXISTS apifull_public_forward_story_lookup
    ON apifull_public_forward_story (source_user_id, source_story_id, id);
