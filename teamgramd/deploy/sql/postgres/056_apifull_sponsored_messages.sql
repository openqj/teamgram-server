-- PostgreSQL 18 state for Telegram sponsored-message preferences, policies,
-- and idempotent view/click/report analytics.

CREATE TABLE IF NOT EXISTS apifull_sponsored_user_setting (
    user_id BIGINT PRIMARY KEY,
    enabled BOOLEAN NOT NULL,
    updated_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE TABLE IF NOT EXISTS apifull_sponsored_event (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id BIGINT NOT NULL,
    event_type TEXT NOT NULL CHECK (char_length(event_type) > 0),
    random_id BYTEA NOT NULL,
    payload JSONB NOT NULL DEFAULT '{}'::jsonb,
    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT uq_apifull_sponsored_event_identity
        UNIQUE (user_id, event_type, random_id)
);
CREATE INDEX IF NOT EXISTS idx_apifull_sponsored_event_user_time
    ON apifull_sponsored_event (user_id, created_at DESC, id DESC);
CREATE INDEX IF NOT EXISTS idx_apifull_sponsored_event_type_time
    ON apifull_sponsored_event (event_type, created_at DESC, id DESC);

CREATE TABLE IF NOT EXISTS apifull_sponsored_channel_policy (
    channel_id BIGINT PRIMARY KEY,
    actor_user_id BIGINT NOT NULL,
    restricted BOOLEAN NOT NULL,
    updated_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP
);
