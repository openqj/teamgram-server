CREATE TABLE IF NOT EXISTS recommendation_feedback_logs (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id BIGINT NOT NULL,
    peer_type INTEGER NOT NULL CHECK (peer_type IN (1, 2, 3)),
    peer_id BIGINT NOT NULL,
    feedback_type INTEGER NOT NULL CHECK (feedback_type BETWEEN 1 AND 5),
    timestamp BIGINT NOT NULL,
    session_id VARCHAR(100) NOT NULL DEFAULT '',
    device_info JSONB NOT NULL DEFAULT '{}'::jsonb
);

CREATE INDEX IF NOT EXISTS recommendation_feedback_logs_user_time_idx
    ON recommendation_feedback_logs (user_id, timestamp DESC);
