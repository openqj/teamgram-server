-- Persist recommendation candidates, policy configuration, and user feedback.
-- Recommendation timestamps are Unix seconds to match the dialog service API.

CREATE TABLE IF NOT EXISTS dialog_recommendations (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id BIGINT NOT NULL,
    peer_type INTEGER NOT NULL CHECK (peer_type IN (1, 2, 3)),
    peer_id BIGINT NOT NULL,
    recommendation_type INTEGER NOT NULL DEFAULT 0,
    weight INTEGER NOT NULL DEFAULT 0,
    score DOUBLE PRECISION NOT NULL DEFAULT 0,
    is_promoted BOOLEAN NOT NULL DEFAULT FALSE,
    promoted_until BIGINT NOT NULL DEFAULT 0,
    promoted_priority INTEGER NOT NULL DEFAULT 0,
    recommended_at BIGINT NOT NULL,
    expires_at BIGINT NOT NULL DEFAULT 0,
    last_updated BIGINT NOT NULL DEFAULT 0,
    shown_count INTEGER NOT NULL DEFAULT 0,
    clicked_count INTEGER NOT NULL DEFAULT 0,
    dismissed BOOLEAN NOT NULL DEFAULT FALSE,
    dismissed_at BIGINT NOT NULL DEFAULT 0,
    deleted BOOLEAN NOT NULL DEFAULT FALSE,
    CONSTRAINT dialog_recommendations_user_peer_key UNIQUE (user_id, peer_type, peer_id)
);

CREATE INDEX IF NOT EXISTS dialog_recommendations_user_active_idx
    ON dialog_recommendations (user_id)
    WHERE deleted = FALSE AND dismissed = FALSE;

CREATE INDEX IF NOT EXISTS dialog_recommendations_promoted_idx
    ON dialog_recommendations (user_id, promoted_priority DESC, weight DESC)
    WHERE deleted = FALSE AND dismissed = FALSE AND is_promoted = TRUE;

CREATE INDEX IF NOT EXISTS dialog_recommendations_weight_idx
    ON dialog_recommendations (user_id, weight DESC, score DESC)
    WHERE deleted = FALSE AND dismissed = FALSE;

CREATE INDEX IF NOT EXISTS dialog_recommendations_expires_idx
    ON dialog_recommendations (expires_at)
    WHERE deleted = FALSE AND expires_at > 0;

CREATE TABLE IF NOT EXISTS recommendation_configs (
    id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    config_key VARCHAR(100) NOT NULL UNIQUE,
    config_value TEXT NOT NULL,
    enabled BOOLEAN NOT NULL DEFAULT TRUE,
    description TEXT NOT NULL DEFAULT '',
    created_at BIGINT NOT NULL DEFAULT 0,
    updated_at BIGINT NOT NULL DEFAULT 0
);

