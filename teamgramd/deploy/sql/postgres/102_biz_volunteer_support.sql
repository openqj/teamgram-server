-- Seed the support peer returned by help.getSupport and persist its intake
-- conversation state per user.
CREATE TABLE IF NOT EXISTS volunteer_support_tickets (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id BIGINT NOT NULL REFERENCES users(id) ON DELETE CASCADE,
    status TEXT NOT NULL DEFAULT 'queued'
        CHECK (status IN ('queued', 'assigned', 'in_progress', 'resolved', 'closed')),
    problem TEXT NOT NULL,
    category TEXT NOT NULL DEFAULT '',
    environment TEXT NOT NULL DEFAULT '',
    assigned_to BIGINT REFERENCES users(id) ON DELETE SET NULL,
    claimed_at TIMESTAMPTZ,
    resolved_at TIMESTAMPTZ,
    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE INDEX IF NOT EXISTS volunteer_support_tickets_queue_idx
    ON volunteer_support_tickets (status, created_at, id);

CREATE TABLE IF NOT EXISTS volunteer_support_sessions (
    user_id BIGINT PRIMARY KEY REFERENCES users(id) ON DELETE CASCADE,
    state TEXT NOT NULL DEFAULT 'idle',
    problem TEXT NOT NULL DEFAULT '',
    category TEXT NOT NULL DEFAULT '',
    environment TEXT NOT NULL DEFAULT '',
    last_message_id INTEGER NOT NULL DEFAULT 0,
    last_reply TEXT NOT NULL DEFAULT '',
    ticket_id BIGINT REFERENCES volunteer_support_tickets(id) ON DELETE SET NULL,
    submitted_at TIMESTAMPTZ,
    updated_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP
);

ALTER TABLE volunteer_support_sessions
    ADD COLUMN IF NOT EXISTS ticket_id BIGINT REFERENCES volunteer_support_tickets(id) ON DELETE SET NULL;

