-- Gift collections are private, owner-scoped groupings of saved gifts.
CREATE TABLE IF NOT EXISTS apifull_gift_collection (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    owner_user_id BIGINT NOT NULL,
    title TEXT NOT NULL,
    position INT NOT NULL DEFAULT 0
);
CREATE INDEX IF NOT EXISTS idx_apifull_gift_collection_owner
    ON apifull_gift_collection (owner_user_id, position, id);

CREATE TABLE IF NOT EXISTS apifull_gift_collection_item (
    collection_id BIGINT NOT NULL REFERENCES apifull_gift_collection(id) ON DELETE CASCADE,
    gift_id BIGINT NOT NULL REFERENCES apifull_gift(id) ON DELETE CASCADE,
    position INT NOT NULL DEFAULT 0,
    PRIMARY KEY (collection_id, gift_id)
);
CREATE INDEX IF NOT EXISTS idx_apifull_gift_collection_item_order
    ON apifull_gift_collection_item (collection_id, position, gift_id);
