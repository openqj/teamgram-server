-- BotFather Mini App registry and conversational wizard state.
ALTER TABLE botfather_sessions
    ADD COLUMN IF NOT EXISTS pending_app_title TEXT NOT NULL DEFAULT '',
    ADD COLUMN IF NOT EXISTS pending_app_short_name TEXT NOT NULL DEFAULT '',
    ADD COLUMN IF NOT EXISTS pending_app_description TEXT NOT NULL DEFAULT '',
    ADD COLUMN IF NOT EXISTS pending_app_url TEXT NOT NULL DEFAULT '';

CREATE TABLE IF NOT EXISTS bot_mini_apps (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    bot_id BIGINT NOT NULL REFERENCES users(id) ON DELETE CASCADE,
    short_name TEXT NOT NULL,
    title TEXT NOT NULL,
    description TEXT NOT NULL DEFAULT '',
    url TEXT NOT NULL,
    domain TEXT NOT NULL DEFAULT '',
    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    UNIQUE (bot_id, short_name)
);

CREATE INDEX IF NOT EXISTS bot_mini_apps_bot_updated_idx
    ON bot_mini_apps (bot_id, updated_at DESC, id DESC);
